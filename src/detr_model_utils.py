import os
import time
import json
import random
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.patches as patches

import torch
from torchmetrics.detection.mean_ap import MeanAveragePrecision
from torchvision.ops import box_iou
from transformers import DetrImageProcessor

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
processor = DetrImageProcessor.from_pretrained("facebook/detr-resnet-50")


def train_detr(
    model,
    model_name,
    train_loader,
    val_loader,
    epochs,
    lr,
    wd,
    eval_threshold=0.1,
):
    model = model.to(device)

    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=wd)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=epochs, eta_min=1e-6
    )

    history = {
        "train_loss": [],
        "val_map": [],
        "val_map_50": [],
        "val_f1": [],
        "time": 0.0,
        "eval_threshold": eval_threshold,
    }

    best_map = 0.0
    early_stop_counter = 0
    patience = 10

    os.makedirs("checkpoints", exist_ok=True)
    os.makedirs("outputs", exist_ok=True)

    start_time = time.time()
    print(
        f"학습 시작 | 모델: {model_name} | Epochs: {epochs} | "
        f"LR: {lr} | Device: {device} | Eval threshold: {eval_threshold}"
    )

    for epoch in range(epochs):
        model.train()
        train_loss = 0.0

        for batch_idx, batch in enumerate(train_loader):
            pixel_values = batch["pixel_values"].to(device)
            pixel_mask = batch["pixel_mask"].to(device)
            labels = [{k: v.to(device) for k, v in t.items()} for t in batch["labels"]]

            outputs = model(
                pixel_values=pixel_values,
                pixel_mask=pixel_mask,
                labels=labels,
            )
            loss = outputs.loss

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            train_loss += loss.item()

            if (batch_idx + 1) % 8 == 0:
                print(".", end="", flush=True)

        train_loss /= len(train_loader)

        val_map, val_map_50, val_f1 = evaluate_detr(
            model=model,
            val_loader=val_loader,
            threshold=eval_threshold,
        )

        scheduler.step()

        history["train_loss"].append(train_loss)
        history["val_map"].append(val_map)
        history["val_map_50"].append(val_map_50)
        history["val_f1"].append(val_f1)

        print(
            f"Epoch [{epoch+1}/{epochs}] | Train Loss: {train_loss:.4f} | "
            f"Val mAP: {val_map:.4f} | Val mAP@50: {val_map_50:.4f} | Val F1: {val_f1:.4f}"
        )

        if val_map > best_map:
            best_map = val_map
            early_stop_counter = 0
            torch.save(model.state_dict(), f"checkpoints/{model_name}.pt")
            print(f"  -> Best model saved (mAP: {best_map:.4f})")
        else:
            early_stop_counter += 1
            if early_stop_counter >= patience:
                print(f"Early stopping at epoch {epoch+1}")
                break

    history["time"] = time.time() - start_time

    with open(f"outputs/{model_name}_history.json", "w") as f:
        json.dump(history, f, indent=4)

    return history


@torch.no_grad()
def evaluate_detr(model, val_loader, threshold=0.1):
    model.eval()

    metric = MeanAveragePrecision(
        iou_thresholds=[0.75, 0.80, 0.85, 0.90, 0.95],
        extended_summary=False,
    )
    metric_50 = MeanAveragePrecision(
        iou_thresholds=[0.50],
        extended_summary=False,
    )

    all_preds = []
    all_targets = []

    for batch in val_loader:
        pixel_values = batch["pixel_values"].to(device)
        pixel_mask = batch["pixel_mask"].to(device)

        outputs = model(
            pixel_values=pixel_values,
            pixel_mask=pixel_mask,
        )

        target_sizes = torch.tensor(
            [[pixel_values.shape[-2], pixel_values.shape[-1]]] * pixel_values.size(0),
            device=device,
        )

        results = processor.post_process_object_detection(
            outputs,
            threshold=threshold,
            target_sizes=target_sizes,
        )

        preds = [
            {
                "boxes": r["boxes"].cpu(),
                "scores": r["scores"].cpu(),
                "labels": r["labels"].cpu(),
            }
            for r in results
        ]

        targets = []
        h, w = pixel_values.shape[-2], pixel_values.shape[-1]

        for t in batch["labels"]:
            gt_boxes = t["boxes"]
            gt_labels = t["class_labels"]

            cx, cy, bw, bh = (
                gt_boxes[:, 0],
                gt_boxes[:, 1],
                gt_boxes[:, 2],
                gt_boxes[:, 3],
            )

            x1 = (cx - bw / 2) * w
            y1 = (cy - bh / 2) * h
            x2 = (cx + bw / 2) * w
            y2 = (cy + bh / 2) * h

            abs_gt_boxes = torch.stack([x1, y1, x2, y2], dim=-1)

            targets.append(
                {
                    "boxes": abs_gt_boxes.cpu(),
                    "labels": gt_labels.cpu(),
                }
            )

        for pred, target in zip(preds, targets):
            all_preds.append(
                {
                    "boxes": pred["boxes"],
                    "scores": pred["scores"],
                    "labels": pred["labels"],
                }
            )
            all_targets.append(
                {
                    "boxes": target["boxes"],
                    "labels": target["labels"],
                }
            )

    metric.update(all_preds, all_targets)
    metric_50.update(all_preds, all_targets)

    result = metric.compute()
    result_50 = metric_50.compute()

    val_map = result["map"].item()
    val_map_50 = result_50["map_50"].item()

    precision, recall = calc_precision_recall(all_preds, all_targets)
    val_f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) > 0 else 0.0

    return val_map, val_map_50, val_f1


def calc_precision_recall(preds, targets, iou_threshold=0.5, score_threshold=0.5):
    tp, fp, fn = 0, 0, 0

    for pred, target in zip(preds, targets):
        scores = pred["scores"]
        keep = scores >= score_threshold
        pred_boxes = pred["boxes"][keep]
        gt_boxes = target["boxes"]

        if len(pred_boxes) == 0 and len(gt_boxes) == 0:
            continue
        elif len(pred_boxes) == 0:
            fn += len(gt_boxes)
            continue
        elif len(gt_boxes) == 0:
            fp += len(pred_boxes)
            continue

        iou = box_iou(pred_boxes, gt_boxes)

        matched_gt = set()
        for pred_idx in range(len(pred_boxes)):
            best_iou, best_gt_idx = iou[pred_idx].max(dim=0)

            if best_iou >= iou_threshold and best_gt_idx.item() not in matched_gt:
                tp += 1
                matched_gt.add(best_gt_idx.item())
            else:
                fp += 1

        fn += len(gt_boxes) - len(matched_gt)

    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    return precision, recall


def plot_history(history, model_name="detr_model"):
    epochs = range(1, len(history["train_loss"]) + 1)

    _, axes = plt.subplots(1, 3, figsize=(15, 4))

    axes[0].plot(epochs, history["train_loss"], label="Train Loss")
    axes[0].set_title("Train Loss")
    axes[0].set_xlabel("Epoch")
    axes[0].set_ylabel("Loss")
    axes[0].legend()

    axes[1].plot(epochs, history["val_map"], label="mAP@0.75:0.95")
    axes[1].plot(epochs, history["val_map_50"], label="mAP@0.5")
    axes[1].set_title("Validation mAP")
    axes[1].set_xlabel("Epoch")
    axes[1].set_ylabel("mAP")
    axes[1].legend()

    axes[2].plot(epochs, history["val_f1"], label="Val F1")
    axes[2].set_title("Validation F1")
    axes[2].set_xlabel("Epoch")
    axes[2].set_ylabel("F1")
    axes[2].legend()

    plt.suptitle(f"{model_name} Training History")
    plt.tight_layout()
    os.makedirs("outputs", exist_ok=True)
    plt.savefig(f"outputs/{model_name}_history.png")
    plt.show()