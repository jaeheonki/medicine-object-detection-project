def train_detr(
    model,
    model_name,
    train_loader,
    val_loader,
    epochs,
    lr,
    wd,
    eval_threshold=0.1,
):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = model.to(device)

    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=wd)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=epochs, eta_min=1e-6
    )

    history = {
        "train_loss": [],
        "val_map": [],
        "val_map_50": [],
        "val_f1": [],
        "time": 0.0,
        "eval_threshold": eval_threshold,
    }

    best_map = 0.0
    early_stop_counter = 0
    patience = 10

    os.makedirs("checkpoints", exist_ok=True)
    os.makedirs("outputs", exist_ok=True)

    start_time = time.time()
    print(
        f"학습 시작 | 모델: {model_name} | Epochs: {epochs} | "
        f"LR: {lr} | Device: {device} | Eval threshold: {eval_threshold}"
    )

    for epoch in range(epochs):
        model.train()
        train_loss = 0.0

        for batch_idx, (images, targets) in enumerate(train_loader):
            pixel_values = torch.stack(images).to(device)
            pixel_mask = torch.ones(pixel_values.shape[0], pixel_values.shape[2], pixel_values.shape[3], dtype=torch.long, device=device)
            labels = [{k: v.to(device) for k, v in t.items()} for t in targets]

            outputs = model(
                pixel_values=pixel_values,
                pixel_mask=pixel_mask,
                labels=labels,
            )
            loss = outputs.loss

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            train_loss += loss.item()

            if (batch_idx + 1) % 8 == 0:
                print(".", end="", flush=True)

        train_loss /= len(train_loader)

        val_map, val_map_50, val_f1 = evaluate_detr(
            model=model,
            val_loader=val_loader,
            threshold=eval_threshold,
        )

        scheduler.step()

        history["train_loss"].append(train_loss)
        history["val_map"].append(val_map)
        history["val_map_50"].append(val_map_50)
        history["val_f1"].append(val_f1)

        print(
            f"Epoch [{epoch+1}/{epochs}] | Train Loss: {train_loss:.4f} | "
            f"Val mAP: {val_map:.4f} | Val mAP@50: {val_map_50:.4f} | Val F1: {val_f1:.4f}"
        )

        if val_map > best_map:
            best_map = val_map
            early_stop_counter = 0
            torch.save(model.state_dict(), f"checkpoints/{model_name}.pt")
            print(f"  -> Best model saved (mAP: {best_map:.4f})")
        else:
            early_stop_counter += 1
            if early_stop_counter >= patience:
                print(f"Early stopping at epoch {epoch+1}")
                break

    history["time"] = time.time() - start_time

    with open(f"outputs/{model_name}_history.json", "w") as f:
        json.dump(history, f, indent=4)

    return history


@torch.no_grad()
def evaluate_detr(model, val_loader, threshold=0.1):
    device = next(model.parameters()).device
    processor = DetrImageProcessor.from_pretrained("facebook/detr-resnet-50")

    model.eval()

    metric = MeanAveragePrecision(iou_thresholds=[0.75, 0.80, 0.85, 0.90, 0.95])
    metric_50 = MeanAveragePrecision(iou_thresholds=[0.50])

    all_preds = []
    all_targets = []

    for _, (images, targets_raw) in enumerate(val_loader):
        pixel_values = torch.stack(images).to(device)
        pixel_mask = torch.ones(pixel_values.shape[0], pixel_values.shape[2], pixel_values.shape[3], dtype=torch.long, device=device)

        outputs = model(
            pixel_values=pixel_values,
            pixel_mask=pixel_mask,
        )

        target_sizes = torch.tensor(
            [[pixel_values.shape[-2], pixel_values.shape[-1]]] * pixel_values.size(0),
            device=device,
        )

        results = processor.post_process_object_detection(
            outputs,
            threshold=threshold,
            target_sizes=target_sizes,
        )

        preds = [
            {
                "boxes": r["boxes"].cpu(),
                "scores": r["scores"].cpu(),
                "labels": r["labels"].cpu(),
            }
            for r in results
        ]

        targets = []
        h, w = pixel_values.shape[-2], pixel_values.shape[-1]

        for t in targets_raw:
            gt_boxes = t["boxes"]
            gt_labels = t["class_labels"]

            cx, cy, bw, bh = (
                gt_boxes[:, 0],
                gt_boxes[:, 1],
                gt_boxes[:, 2],
                gt_boxes[:, 3],
            )

            x1 = (cx - bw / 2) * w
            y1 = (cy - bh / 2) * h
            x2 = (cx + bw / 2) * w
            y2 = (cy + bh / 2) * h

            abs_gt_boxes = torch.stack([x1, y1, x2, y2], dim=-1)

            targets.append(
                {
                    "boxes": abs_gt_boxes.cpu(),
                    "labels": gt_labels.cpu(),
                }
            )

        for pred, target in zip(preds, targets):
            all_preds.append(pred)
            all_targets.append(target)

    metric.update(all_preds, all_targets)
    metric_50.update(all_preds, all_targets)

    result = metric.compute()
    result_50 = metric_50.compute()

    val_map = result["map"].item()
    val_map_50 = result_50["map_50"].item()

    precision, recall = calc_precision_recall(all_preds, all_targets)
    val_f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) > 0 else 0.0

    return val_map, val_map_50, val_f1


def calc_precision_recall(preds, targets, iou_threshold=0.5, score_threshold=0.5):
    tp, fp, fn = 0, 0, 0

    for pred, target in zip(preds, targets):
        scores = pred["scores"]
        keep = scores >= score_threshold
        pred_boxes = pred["boxes"][keep]
        gt_boxes = target["boxes"]

        if len(pred_boxes) == 0 and len(gt_boxes) == 0:
            continue
        elif len(pred_boxes) == 0:
            fn += len(gt_boxes)
            continue
        elif len(gt_boxes) == 0:
            fp += len(pred_boxes)
            continue

        iou = box_iou(pred_boxes, gt_boxes)

        matched_gt = set()
        for pred_idx in range(len(pred_boxes)):
            best_iou, best_gt_idx = iou[pred_idx].max(dim=0)

            if best_iou >= iou_threshold and best_gt_idx.item() not in matched_gt:
                tp += 1
                matched_gt.add(best_gt_idx.item())
            else:
                fp += 1

        fn += len(gt_boxes) - len(matched_gt)

    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    return precision, recall


def plot_predictions_detr(model, dataset, model_name, threshold=0.5, n=5):
    device = next(model.parameters()).device
    processor = DetrImageProcessor.from_pretrained("facebook/detr-resnet-50")

    checkpoint_path = f"checkpoints/{model_name}.pt"
    model.load_state_dict(torch.load(checkpoint_path, map_location=device, weights_only=True))
    model.eval()

    indices = random.sample(range(len(dataset)), min(n, len(dataset)))

    _, axes = plt.subplots(n, 3, figsize=(15, n * 4))

    with torch.no_grad():
        for row, idx in enumerate(indices):
            image, target = dataset[idx]

            pixel_values = image.unsqueeze(0).to(device)
            pixel_mask = torch.ones(1, pixel_values.shape[2], pixel_values.shape[3], dtype=torch.long, device=device)

            outputs = model(pixel_values=pixel_values, pixel_mask=pixel_mask)

            target_sizes = torch.tensor([[pixel_values.shape[-2], pixel_values.shape[-1]]], device=device)
            results = processor.post_process_object_detection(outputs, threshold=threshold, target_sizes=target_sizes)

            pred_boxes = results[0]["boxes"].cpu()
            pred_scores = results[0]["scores"].cpu()
            pred_labels = results[0]["labels"].cpu()

            h, w = image.shape[-2], image.shape[-1]
            gt_boxes_norm = target["boxes"]
            gt_labels = target["class_labels"]
            cx, cy, bw, bh = gt_boxes_norm[:, 0], gt_boxes_norm[:, 1], gt_boxes_norm[:, 2], gt_boxes_norm[:, 3]
            gt_boxes = torch.stack([
                (cx - bw / 2) * w, (cy - bh / 2) * h,
                (cx + bw / 2) * w, (cy + bh / 2) * h,
            ], dim=-1).cpu()

            img_np = image.permute(1, 2, 0).cpu().numpy()
            img_np = np.clip(img_np, 0, 1)

            axes[row, 0].imshow(img_np)
            axes[row, 0].set_title("Original")
            axes[row, 0].axis("off")

            axes[row, 1].imshow(img_np)
            for box, score, label in zip(pred_boxes, pred_scores, pred_labels):
                x1, y1, x2, y2 = box
                color = "red"
                if len(gt_boxes) > 0:
                    iou = box_iou(box.unsqueeze(0), gt_boxes)[0]
                    best_idx = iou.argmax().item()
                    if iou[best_idx] >= 0.5 and gt_labels[best_idx].item() == label.item():
                        color = "green"
                rect = patches.Rectangle((x1, y1), x2 - x1, y2 - y1, linewidth=2, edgecolor=color, facecolor="none")
                axes[row, 1].add_patch(rect)
                axes[row, 1].text(x1, y1, f"cls:{label.item()} {score:.2f}", color=color, fontsize=8)
            axes[row, 1].set_title("Prediction (green=correct, red=wrong)")
            axes[row, 1].axis("off")

            axes[row, 2].imshow(img_np)
            for box, label in zip(gt_boxes, gt_labels):
                x1, y1, x2, y2 = box
                rect = patches.Rectangle((x1, y1), x2 - x1, y2 - y1, linewidth=2, edgecolor="green", facecolor="none")
                axes[row, 2].add_patch(rect)
                axes[row, 2].text(x1, y1, f"cls:{label.item()}", color="green", fontsize=8)
            axes[row, 2].set_title("Ground Truth")
            axes[row, 2].axis("off")

    plt.suptitle(f"{model_name} Predictions")
    plt.tight_layout()
    os.makedirs("outputs", exist_ok=True)
    plt.savefig(f"outputs/{model_name}_predictions.png")
    print("예측 시각화 저장 완료:", f"outputs/{model_name}_predictions.png")


def prepare_detr_data(train_json, val_json, image_dir, batch_size=2):
    from detr_dataset import PillDetrDataset, detr_collate_fn

    processor = DetrImageProcessor.from_pretrained("facebook/detr-resnet-50")

    train_dataset = PillDetrDataset(train_json, image_dir, processor)
    val_dataset = PillDetrDataset(val_json, image_dir, processor)

    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True, collate_fn=detr_collate_fn)
    val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False, collate_fn=detr_collate_fn)

    categories = train_dataset.categories
    id2label = {i: cat["name"] for i, cat in enumerate(categories)}
    label2id = {v: k for k, v in id2label.items()}

    return train_loader, val_loader, val_dataset, id2label, label2id


def build_detr_model(id2label, label2id):
    model = DetrForObjectDetection.from_pretrained(
        "facebook/detr-resnet-50",
        num_labels=len(id2label),
        id2label=id2label,
        label2id=label2id,
        ignore_mismatched_sizes=True,
    )
    return model


def print_summary_detr(history, model_name):
    val_map_list = history["val_map"]
    val_map_50_list = history["val_map_50"]
    val_f1_list = history["val_f1"]
    total_time = history["time"]

    best_map = max(val_map_list)
    best_map_50 = max(val_map_50_list)
    best_f1 = max(val_f1_list)

    best_map_epoch = val_map_list.index(best_map) + 1
    best_map_50_epoch = val_map_50_list.index(best_map_50) + 1
    best_f1_epoch = val_f1_list.index(best_f1) + 1

    hours = int(total_time // 3600)
    minutes = int((total_time % 3600) // 60)
    seconds = int(total_time % 60)

    print(f"\n{'='*50}")
    print(f"  {model_name} 학습 결과 요약")
    print(f"{'='*50}")
    print(f"  Best mAP@0.75:0.95 : {best_map:.4f}  (Epoch {best_map_epoch})")
    print(f"  Best mAP@0.5       : {best_map_50:.4f}  (Epoch {best_map_50_epoch})")
    print(f"  Best F1 Score      : {best_f1:.4f}  (Epoch {best_f1_epoch})")
    print(f"  총 학습 시간       : {hours}h {minutes}m {seconds}s")
    print(f"{'='*50}\n")


