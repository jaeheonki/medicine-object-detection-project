import os
import json
import random
from collections import defaultdict
from pathlib import Path

import torch
from PIL import Image
from torch.utils.data import Dataset
from transformers import DetrImageProcessor

processor = DetrImageProcessor.from_pretrained("facebook/detr-resnet-50")


def load_coco_json(json_path):
    with open(json_path, "r", encoding="utf-8") as f:
        coco = json.load(f)

    images = coco["images"]
    annotations = coco["annotations"]
    categories = coco["categories"]

    image_id_to_annotations = defaultdict(list)
    for ann in annotations:
        image_id_to_annotations[ann["image_id"]].append(ann)

    return {
        "images": images,
        "annotations": annotations,
        "categories": categories,
        "image_id_to_annotations": image_id_to_annotations,
    }


class PillDetrDataset(Dataset):
    def __init__(self, json_path, image_dir, processor=None):
        self.data = load_coco_json(json_path)
        self.image_dir = image_dir
        self.processor = processor or DetrImageProcessor.from_pretrained(
            "facebook/detr-resnet-50"
        )

        self.images = self.data["images"]
        self.image_id_to_annotations = self.data["image_id_to_annotations"]
        self.categories = self.data["categories"]

        sorted_ids = sorted(cat["id"] for cat in self.categories)
        self.category_map = {old_id: new_id for new_id, old_id in enumerate(sorted_ids)}

    def __len__(self):
        return len(self.images)

    def __getitem__(self, idx):
        image_info = self.images[idx]
        image_id = image_info["id"]
        file_name = image_info["file_name"]

        image_path = os.path.join(self.image_dir, file_name)
        image = Image.open(image_path).convert("RGB")
        image = image.resize((512, 512))

        anns = self.image_id_to_annotations.get(image_id, [])

        remapped_anns = []
        for ann in anns:
            category_id = ann["category_id"]
            if category_id not in self.category_map:
                continue

            new_ann = ann.copy()
            new_ann["category_id"] = self.category_map[category_id]
            remapped_anns.append(new_ann)

        target = {
            "image_id": image_id,
            "annotations": remapped_anns,
        }

        encoding = self.processor(
            images=image,
            annotations=target,
            return_tensors="pt",
        )

        pixel_values = encoding["pixel_values"].squeeze(0)
        labels = encoding["labels"][0]

        return pixel_values, labels


def detr_collate_fn(batch):
    pixel_values = [item[0] for item in batch]
    labels = [item[1] for item in batch]
    return pixel_values, labels


def split_coco_json(merged_ann_dir, output_dir, val_ratio=0.2, seed=42):
    merged_ann_dir = Path(merged_ann_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    train_out = output_dir / "train_split.json"
    val_out = output_dir / "val_split.json"

    if train_out.exists() and val_out.exists():
        print("COCO split JSON이 이미 존재합니다.")
        return str(train_out), str(val_out)

    category_dict = {}
    json_files = sorted(merged_ann_dir.glob("*.json"))

    for json_file in json_files:
        with open(json_file, "r", encoding="utf-8") as f:
            data = json.load(f)
        for cat in data.get("raw_categories", []):
            category_dict[cat["id"]] = cat["name"]

    sorted_cat_ids = sorted(category_dict.keys())
    class_map = {cat_id: idx for idx, cat_id in enumerate(sorted_cat_ids)}
    categories = [{"id": idx, "name": category_dict[cat_id]} for idx, cat_id in enumerate(sorted_cat_ids)]

    all_images = []
    all_annotations = []
    ann_id = 1

    for img_id, json_file in enumerate(json_files, start=1):
        with open(json_file, "r", encoding="utf-8") as f:
            data = json.load(f)

        all_images.append({
            "id": img_id,
            "file_name": data["file_name"],
            "width": data["width"],
            "height": data["height"],
        })

        for ann in data.get("merged_annotations", []):
            cat_id = ann["raw_annotation"]["category_id"]
            if cat_id not in class_map:
                continue
            x, y, w, h = ann["bbox_xywh"]
            if w <= 0 or h <= 0:
                continue
            all_annotations.append({
                "id": ann_id,
                "image_id": img_id,
                "category_id": class_map[cat_id],
                "bbox": [x, y, w, h],
                "area": w * h,
                "iscrowd": 0,
            })
            ann_id += 1

    random.seed(seed)
    image_ids = [img["id"] for img in all_images]
    random.shuffle(image_ids)
    val_size = int(len(image_ids) * val_ratio)
    val_ids = set(image_ids[:val_size])
    train_ids = set(image_ids[val_size:])

    def build_coco(ids):
        images = [img for img in all_images if img["id"] in ids]
        annotations = [ann for ann in all_annotations if ann["image_id"] in ids]
        return {"images": images, "annotations": annotations, "categories": categories}

    with open(train_out, "w", encoding="utf-8") as f:
        json.dump(build_coco(train_ids), f, ensure_ascii=False)

    with open(val_out, "w", encoding="utf-8") as f:
        json.dump(build_coco(val_ids), f, ensure_ascii=False)

    print(f"train: {len(train_ids)}개, val: {len(val_ids)}개")
    print(f"저장 완료: {train_out}, {val_out}")
    return str(train_out), str(val_out)