import os
import json
import torch
import numpy as np
from PIL import Image
from collections import defaultdict

import matplotlib.pyplot as plt
import matplotlib.patches as patches

from torch.utils.data import Dataset, DataLoader
from torchvision.transforms import functional as F

from transformers import DetrImageProcessor, DetrForObjectDetection

"""# 경로 설정"""

# 예시 경로
TRAIN_JSON = "/content/train_merged.json"
VAL_JSON = "/content/val_merged.json"
IMAGE_DIR = "/content/images"

DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("DEVICE:", DEVICE)

"""# COCO json 읽는 함수"""

def load_coco_json(json_path):
    with open(json_path, "r", encoding="utf-8") as f:
        coco = json.load(f)

    images = coco["images"]
    annotations = coco["annotations"]
    categories = coco["categories"]

    image_id_to_info = {img["id"]: img for img in images}

    image_id_to_annotations = defaultdict(list)
    for ann in annotations:
        image_id_to_annotations[ann["image_id"]].append(ann)

    category_id_to_name = {cat["id"]: cat["name"] for cat in categories}
    category_ids = sorted(category_id_to_name.keys())

    return {
        "images": images,
        "annotations": annotations,
        "categories": categories,
        "image_id_to_info": image_id_to_info,
        "image_id_to_annotations": image_id_to_annotations,
        "category_id_to_name": category_id_to_name,
        "category_ids": category_ids,
    }

"""# DETR Dataset"""

class PillDetrDataset(Dataset):
    def __init__(self, json_path, image_dir, processor):
        self.data = load_coco_json(json_path)
        self.image_dir = image_dir
        self.processor = processor

        self.images = self.data["images"]
        self.image_id_to_annotations = self.data["image_id_to_annotations"]

    def __len__(self):
        return len(self.images)

    def __getitem__(self, idx):
        image_info = self.images[idx]
        image_id = image_info["id"]
        file_name = image_info["file_name"]

        image_path = os.path.join(self.image_dir, file_name)
        image = Image.open(image_path).convert("RGB")

        anns = self.image_id_to_annotations.get(image_id, [])

        # COCO 스타일 target
        target = {
            "image_id": image_id,
            "annotations": anns
        }

        encoding = self.processor(
            images=image,
            annotations=target,
            return_tensors="pt"
        )

        pixel_values = encoding["pixel_values"].squeeze(0)
        labels = encoding["labels"][0]

        return {
            "pixel_values": pixel_values,
            "labels": labels,
            "image": image,
            "image_id": image_id,
            "file_name": file_name
        }

"""# collate_fn"""

def collate_fn(batch):
    pixel_values = [item["pixel_values"] for item in batch]
    labels = [item["labels"] for item in batch]

    encoding = processor.pad(pixel_values, return_tensors="pt")

    return {
        "pixel_values": encoding["pixel_values"],
        "pixel_mask": encoding["pixel_mask"],
        "labels": labels,
        "images": [item["image"] for item in batch],
        "image_ids": [item["image_id"] for item in batch],
        "file_names": [item["file_name"] for item in batch]
    }

"""# Processor / dataset / dataloader"""

processor = DetrImageProcessor.from_pretrained("facebook/detr-resnet-50")

train_meta = load_coco_json(TRAIN_JSON)
val_meta = load_coco_json(VAL_JSON)

num_classes = len(train_meta["categories"])
print("num_classes:", num_classes)

train_dataset = PillDetrDataset(TRAIN_JSON, IMAGE_DIR, processor)
val_dataset = PillDetrDataset(VAL_JSON, IMAGE_DIR, processor)

train_loader = DataLoader(
    train_dataset,
    batch_size=4,
    shuffle=True,
    collate_fn=collate_fn
)

val_loader = DataLoader(
    val_dataset,
    batch_size=4,
    shuffle=False,
    collate_fn=collate_fn
)

"""# label mapping 만들기"""

id2label = {cat["id"]: cat["name"] for cat in train_meta["categories"]}
label2id = {v: k for k, v in id2label.item()}

print(id2label)

"""# 모델 로드"""

model = DetrForObjectDetection.from_pretrained(
    "facebook/detr-resnet-50",
    num_labels=num_classes,
    ignore_mismatched_sizes=True,
    id2label=id2label,
    label2id=label2id
)

model.to(DEVICE)

"""# optimizer"""

optimizer = torch.optim.AdamW(model.parameters(), lr=1e-4, weight_decay=1e-4)

"""# train_one_epoch"""

def train_one_epoch(model, loader, optimizer, device):
    model.train()

    total_loss = 0.0

    for batch in loader:
        pixel_values = batch["pixel_values"].to(device)
        pixel_mask = batch["pixel_mask"].to(device)
        labels = [{k: v.to(device) for k, v in t.items()} for t in batch["labels"]]

        outputs = model(
            pixel_values=pixel_values,
            pixel_mask=pixel_mask,
            labels=labels
        )

        loss = outputs.loss

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        total_loss += loss.item()

    return total_loss / len(loader)

"""# validation"""

@torch.no_grad()
def validate(model, loader, device):
    model.eval()

    total_loss = 0.0

    for batch in loader:
        pixel_values = batch["pixel_values"].to(device)
        pixel_mask = batch["pixel_mask"].to(device)
        labels = [{k: v.to(device) for k, v in t.items()} for t in batch["labels"]]

        outputs = model(
            pixel_values=pixel_values,
            pixel_mask=pixel_mask,
            labels=labels
        )

        total_loss += outputs.loss.item()

    return total_loss / len(loader)

"""# 학습 루프"""

num_epochs = 10

history = {
    "train_loss": [],
    "val_loss": []
}

best_val_loss = float("inf")
os.makedirs("results", exist_ok=True)

for epoch in range(num_epochs):
    train_loss = train_one_epoch(model, train_loader, optimizer, DEVICE)
    val_loss = validate(model, val_loader, DEVICE)

    history["train_loss"].append(train_loss)
    history["val_loss"].append(val_loss)

    print(f"[Epoch {epoch+1}/{num_epochs}]")
    print(f"Train Loss: {train_loss:.4f}")
    print(f"Val Loss:   {val_loss:.4f}")
    print("-" * 50)

    if val_loss < best_val_loss:
        best_val_loss = val_loss
        torch.save(model.state_dict(), "results/detr_best.pth")
        print("Best model saved.")

