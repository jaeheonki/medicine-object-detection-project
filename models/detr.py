"""# 예측 결과 시각화"""

@torch.no_grad()
def visualize_predictions(model, dataset, processor, device, id2label, idx=0, threshold=0.7):
    model.eval()

    sample = dataset[idx]
    image = sample["image"]

    encoding = processor(images=image, return_tensors="pt")
    pixel_values = encoding["pixel_values"].to(device)
    pixel_mask = encoding["pixel_mask"].to(device) if "pixel_mask" in encoding else None

    outputs = model(pixel_values=pixel_values, pixel_mask=pixel_mask)

    width, height = image.size
    target_sizes = torch.tensor([[height, width]]).to(device)

    results = processor.post_process_object_detection(
        outputs,
        threshold=threshold,
        target_sizes=target_sizes
    )[0]

    plt.figure(figsize=(10, 10))
    plt.imshow(image)
    ax = plt.gca()

    for score, label, box in zip(results["scores"], results["labels"], results["boxes"]):
        x1, y1, x2, y2 = box.tolist()
        w = x2 - x1
        h = y2 - y1

        rect = patches.Rectangle(
            (x1, y1), w, h,
            linewidth=2,
            edgecolor="red",
            facecolor="none"
        )
        ax.add_patch(rect)

        label_id = label.item()
        class_name = id2label.get(label_id, str(label_id))
        ax.text(
            x1, y1 - 5,
            f"{class_name}: {score:.2f}",
            color="red",
            fontsize=10,
            bbox=dict(facecolor="white", alpha=0.7)
        )

    plt.axis("off")
    plt.tight_layout()
    plt.show()

