import torch
from importlib import reload
from torch.utils.data import DataLoader
from transformers import DetrForObjectDetection, DetrImageProcessor

import src.detr_dataset
reload(src.detr_dataset)

from src.detr_dataset import PillDetrDataset, detr_collate_fn
from src.detr_model_utils import train_detr


# =========================
# 경로 설정
# =========================
TRAIN_JSON = "/content/train_split.json"
VAL_JSON = "/content/val_split.json"
IMAGE_DIR = "/content/ai10-level1-project/sprint_ai_project1_data/train_images"

# =========================
# 하이퍼파라미터
# =========================
BATCH_SIZE = 2
EPOCHS = 5
LR = 0.0001
WD = 1e-4

DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


def main():
    print("DEVICE:", DEVICE)

    processor = DetrImageProcessor.from_pretrained("facebook/detr-resnet-50")

    train_dataset = PillDetrDataset(TRAIN_JSON, IMAGE_DIR, processor)
    val_dataset = PillDetrDataset(VAL_JSON, IMAGE_DIR, processor)

    train_loader = DataLoader(
        train_dataset,
        batch_size=BATCH_SIZE,
        shuffle=True,
        collate_fn=detr_collate_fn,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=BATCH_SIZE,
        shuffle=False,
        collate_fn=detr_collate_fn,
    )

    # 배치 확인
    batch = next(iter(train_loader))
    print("batch type:", type(batch))
    print("batch keys:", batch.keys())
    print("pixel_values shape:", batch["pixel_values"].shape)
    print("pixel_mask shape:", batch["pixel_mask"].shape)
    print("labels len:", len(batch["labels"]))

    categories = train_dataset.categories
    id2label = {i: cat["name"] for i, cat in enumerate(categories)}
    label2id = {v: k for k, v in id2label.items()}

    print("num_classes:", len(id2label))

    model = DetrForObjectDetection.from_pretrained(
        "facebook/detr-resnet-50",
        num_labels=len(id2label),
        id2label=id2label,
        label2id=label2id,
        ignore_mismatched_sizes=True,
    )

    history = train_detr(
        model=model,
        model_name="detr_pill_thr01",
        train_loader=train_loader,
        val_loader=val_loader,
        epochs=EPOCHS,
        lr=LR,
        wd=WD,
        eval_threshold=0.1,
    )

    print("학습 완료")
    return history


if __name__ == "__main__":
    main()