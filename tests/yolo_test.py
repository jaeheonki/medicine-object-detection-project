import os
import pandas as pd
import matplotlib.pyplot as plt

# -----------------------------
# 1. 가장 최근 학습 결과 폴더 찾기
# -----------------------------
base_dir = "/content/runs/detect"

train_dirs = sorted(
    [d for d in os.listdir(base_dir) if d.startswith("train")]
)

last_train_dir = train_dirs[-1]
result_dir = os.path.join(base_dir, last_train_dir)
csv_path = os.path.join(result_dir, "results.csv")

print("result_dir:", result_dir)
print("csv_path:", csv_path)

# -----------------------------
# 2. results.csv 읽기
# -----------------------------
df = pd.read_csv(csv_path)

# 컬럼명 앞뒤 공백 제거
df.columns = df.columns.str.strip()

print(df.columns.tolist())

# -----------------------------
# 3. F1 계산
# -----------------------------
precision_col = "metrics/precision(B)"
recall_col = "metrics/recall(B)"

df["val_f1"] = (
    2 * df[precision_col] * df[recall_col]
    / (df[precision_col] + df[recall_col] + 1e-8)
)

# -----------------------------
# 4. train loss 계산
# -----------------------------
df["train_loss_total"] = (
    df["train/box_loss"] +
    df["train/cls_loss"] +
    df["train/dfl_loss"]
)

epochs = range(1, len(df) + 1)

# -----------------------------
# 5. 그래프 시각화
# -----------------------------
plt.figure(figsize=(18, 5))

# (1) Train Loss
plt.subplot(1, 3, 1)
plt.plot(epochs, df["train_loss_total"], label="Train Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.title("Train Loss")
plt.legend()

# (2) Validation mAP
plt.subplot(1, 3, 2)
plt.plot(epochs, df["metrics/mAP50-95(B)"], label="mAP@0.5:0.95")
plt.plot(epochs, df["metrics/mAP50(B)"], label="mAP@0.5")
plt.xlabel("Epoch")
plt.ylabel("mAP")
plt.title("Validation mAP")
plt.legend()

# (3) Validation F1
plt.subplot(1, 3, 3)
plt.plot(epochs, df["val_f1"], label="Val F1")
plt.xlabel("Epoch")
plt.ylabel("F1")
plt.title("Validation F1")
plt.legend()

plt.tight_layout()
plt.show()

import random
